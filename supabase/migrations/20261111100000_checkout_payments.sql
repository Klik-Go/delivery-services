-- Phase 5: checkout and payments (docs/BUILD_PLAN.md §6 Phase 5, docs/BUSINESS.md §5.2 steps 1, 6-7).
--
-- Orders, payments, webhook_events and the balanced ledger exist since Phase 1. This adds what
-- placing and paying for an order needs on top: an idempotency key per customer, the gateway's
-- checkout link and fee on payments, refunds, a liability account for money held between payment
-- and delivery, platform-made cancellations, readable order codes and the unpaid-order timeout.

-- ---------------------------------------------------------------------------
-- Readable order codes (KG-XXXXXX) generated by the database, so every writer gets a unique one.
-- No 0/O/1/I so codes read well over the phone.
-- ---------------------------------------------------------------------------
create function private.new_order_code() returns text
language plpgsql volatile set search_path = '' as $$
declare
  v_alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  v_code text;
begin
  loop
    v_code := 'KG-';
    for i in 1..6 loop
      v_code := v_code || substr(v_alphabet, 1 + floor(random() * length(v_alphabet))::int, 1);
    end loop;
    exit when not exists (select 1 from public.orders o where o.code = v_code);
  end loop;
  return v_code;
end;
$$;
alter table public.orders alter column code set default private.new_order_code();

-- ---------------------------------------------------------------------------
-- Place-order idempotency: the same customer + Idempotency-Key always means the same order.
-- request_hash (SHA-256 of the normalised request) tells a retry from a different order that
-- reused a key by mistake.
-- ---------------------------------------------------------------------------
alter table public.orders
  add column idempotency_key text check (idempotency_key ~ '^[A-Za-z0-9_-]{16,100}$'),
  add column request_hash text check (request_hash ~ '^[0-9a-f]{64}$'),
  add constraint orders_idempotency_pair check ((idempotency_key is null) = (request_hash is null));
create unique index orders_customer_idempotency_key on public.orders (customer_id, idempotency_key)
  where idempotency_key is not null;

-- Cancellations the platform makes on its own (an unpaid order timing out, later the merchant
-- acceptance SLA) have no human actor or role; every other cancellation still needs one.
alter table public.orders drop constraint orders_cancel_has_reason;
alter table public.orders add constraint orders_cancel_has_reason check (
  status <> 'cancelled'
  or (cancel_reason is not null
      and (cancelled_by_role is not null or cancel_reason in ('payment_timeout', 'merchant_timeout')))
);

-- ---------------------------------------------------------------------------
-- Payments: where the customer pays, what the gateway charged, how much went back.
-- ---------------------------------------------------------------------------
alter table public.payments
  add column checkout_url text check (char_length(checkout_url) <= 2000),
  add column gateway_payment_id text check (char_length(gateway_payment_id) <= 100),
  add column fee_centavos integer check (fee_centavos >= 0),
  add column refunded_centavos integer not null default 0 check (refunded_centavos >= 0),
  add column paid_at timestamptz,
  add constraint payments_refund_within_amount check (refunded_centavos <= amount_centavos),
  add constraint payments_paid_has_time check (status not in ('paid', 'refunded', 'partially_refunded') or paid_at is not null);
create unique index payments_one_per_order on public.payments (order_id);

-- ---------------------------------------------------------------------------
-- Refunds: one row per refund (full or partial) so retries and refund webhooks stay idempotent.
-- ---------------------------------------------------------------------------
create type public.refund_status as enum ('pending', 'succeeded', 'failed');

create table public.refunds (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete restrict,
  payment_id uuid not null references public.payments (id) on delete restrict,
  amount_centavos integer not null check (amount_centavos > 0),
  reason text not null check (char_length(reason) between 1 and 300),
  status public.refund_status not null default 'pending',
  gateway_ref text check (char_length(gateway_ref) <= 100),
  -- Null when the platform refunded on its own (a payment that arrived after the order timed out).
  requested_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index refunds_order_idx on public.refunds (order_id);
create unique index refunds_gateway_ref on public.refunds (payment_id, gateway_ref) where gateway_ref is not null;
create trigger refunds_updated_at before update on public.refunds
  for each row execute function private.set_updated_at();
alter table public.refunds enable row level security;
-- Visible exactly when the order is (customer sees the refund status of a cancelled order).
-- Written by the server only: no client insert/update policy or grant.
create policy refunds_select on public.refunds for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id));
-- Same convention as Phase 1 tables: grant to both roles and let RLS decide (anon sees nothing).
grant select on public.refunds to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Ledger: money held for the customer between payment and delivery. A captured online payment
-- is a deposit (owed back on cancellation) until the order is delivered and settled into
-- merchant, rider and platform shares.
-- ---------------------------------------------------------------------------
alter type public.ledger_account add value if not exists 'customer_deposits';

-- ---------------------------------------------------------------------------
-- Unpaid online orders are cancelled after a timeout (default 15 minutes) and their promo
-- redemption is released, so the code can be used again. A payment that still arrives later is
-- refunded by the webhook handler (PaymentEventService).
-- ---------------------------------------------------------------------------
create function private.cancel_unpaid_orders(p_after interval default interval '15 minutes')
returns integer
language plpgsql security definer set search_path = '' as $$
declare
  v_count integer;
begin
  perform set_config('klikgo.actor_id', '', true);
  perform set_config('klikgo.actor_role', '', true);
  perform set_config('klikgo.event_meta', '{"reason":"payment_timeout","by":"system"}', true);

  with expired as (
    update public.orders o
       set status = 'cancelled', cancel_reason = 'payment_timeout', payment_status = 'failed'
     where o.status = 'awaiting_payment' and o.created_at < now() - p_after
    returning o.id
  ), failed_payments as (
    update public.payments p set status = 'failed'
      from expired e
     where p.order_id = e.id and p.status in ('pending', 'processing')
    returning p.id
  ), released as (
    delete from public.promo_redemptions r using expired e where r.order_id = e.id returning r.id
  )
  select count(*) into v_count from expired;
  return v_count;
end;
$$;
revoke all on function private.cancel_unpaid_orders(interval) from public;

select cron.schedule('cancel-unpaid-orders', '* * * * *', $$select private.cancel_unpaid_orders()$$);
